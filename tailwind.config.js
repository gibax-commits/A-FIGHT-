// true にすると bg-red-900/40 のような「色 + 透過」を全パレット分出力する。
// false: 約 970KB (gzip 100KB) / true: 約 1.8MB (gzip 179KB)
// false でも、旧 styles.css に入っていた透過クラスは LEGACY 側に含まれている。
const WITH_OPACITY = false;

// ── 透過付きクラスの生成 ────────────────────────────────
// safelist の pattern は "/40" のようなモディファイアまでは展開してくれないので、
// 必要なら文字列として列挙する必要がある。
const PALETTES = ['slate','gray','zinc','neutral','stone','red','orange','amber','yellow','lime',
                  'green','emerald','teal','cyan','sky','blue','indigo','violet','purple','fuchsia','pink','rose'];
const SHADES = ['50','100','200','300','400','500','600','700','800','900','950'];
const buildOpacity = () => {
  const out = [];
  const push = (u, steps) => {
    for (const s of steps) {
      out.push(`${u}-black/${s}`, `${u}-white/${s}`);
      for (const p of PALETTES) for (const sh of SHADES) out.push(`${u}-${p}-${sh}/${s}`);
    }
  };
  ['text','bg','border'].forEach(u => push(u, [5,10,20,25,30,40,50,60,70,75,80,90]));
  ['from','via','to'].forEach(u => push(u, [30,50,70]));
  return out;
};

